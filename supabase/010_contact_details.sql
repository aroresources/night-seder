updated as (
  update people p
  set phone    = coalesce(nullif(btrim(p.phone), ''), i.phone),
      email    = coalesce(nullif(btrim(p.email), ''), i.email),
      address  = coalesce(nullif(btrim(p.address), ''), i.address),
      birthday = coalesce(p.birthday, i.birthday)
  from imported i
  where p.name = i.name
  returning p.name, p.phone, p.email, p.address, p.birthday
)
select
  (select count(*) from imported)                        as "names on the list",
  (select count(*) from updated)                         as "matched a person",
  (select count(*) from updated where phone is not null) as "now has a phone",
  (select count(*) from updated where email is not null) as "now has an email",
  (select count(*) from updated where address is not null) as "now has an address",
  (select count(*) from updated where birthday is not null) as "now has a birthday",
  (select coalesce(string_agg(i.name, ', ' order by i.name), 'none')
     from imported i
    where not exists (select 1 from updated u where u.name = i.name))
